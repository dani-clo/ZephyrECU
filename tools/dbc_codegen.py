#!/usr/bin/env python3
"""Generate the bounded Classical CAN subset used by can_comm; --check never writes."""
import argparse
from decimal import Decimal, ROUND_CEILING, ROUND_FLOOR
import math
from pathlib import Path
import re
import sys

import cantools
import yaml

ROOT = Path(__file__).resolve().parents[1]
BANNER = "/* Generated by tools/dbc_codegen.py; do not edit. */\n"


class UniqueLoader(yaml.SafeLoader):
    """Reject duplicate policy keys rather than silently overriding them."""


def unique_mapping(loader, node):
    result = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node)
        if key in result:
            raise ValueError(f"duplicate policy key: {key}")
        result[key] = loader.construct_object(value_node)
    return result


UniqueLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, unique_mapping)


def ident(name):
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name):
        raise ValueError(f"unsupported C identifier: {name}")
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()


def keys(value, expected, label):
    if not isinstance(value, dict) or set(value) != set(expected):
        raise ValueError(f"{label}: expected exactly {sorted(expected)}")


def milliseconds(value, label, allow_zero=False):
    if type(value) is not int or not (0 if allow_zero else 1) <= value <= 2147483647:
        raise ValueError(f"{label}: expected bounded integer milliseconds")
    return value


def bit_positions(signal):
    if signal.byte_order == "little_endian":
        return list(range(signal.start, signal.start + signal.length))
    position = signal.start
    bits = []
    for _ in range(signal.length):
        bits.append(position)
        position = position + 15 if position % 8 == 0 else position - 1
    return list(reversed(bits))


def model(dbc, policy):
    database = cantools.database.load_file(dbc, database_format="dbc", strict=True,
                                            sort_signals=None)
    config = yaml.load(Path(policy).read_text(), Loader=UniqueLoader)
    keys(config, ("node", "pdus"), "policy")
    if config["node"] not in {node.name for node in database.nodes}:
        raise ValueError("policy node not declared in DBC")
    messages = sorted(database.messages, key=lambda m: (m.frame_id, m.is_extended_frame))
    if not messages or len(messages) > 32:
        raise ValueError("expected 1..32 messages")
    keys(config["pdus"], [m.name for m in messages], "PDU policy")
    names, routes, pdus, signals = set(), set(), [], []
    for message in messages:
        name = ident(message.name)
        if name in names or (message.frame_id, message.is_extended_frame) in routes:
            raise ValueError("duplicate normalized message name or CAN route")
        names.add(name)
        routes.add((message.frame_id, message.is_extended_frame))
        if message.is_fd or not 1 <= message.length <= 8 or message.is_container:
            raise ValueError(f"{message.name}: only non-container Classical CAN DLC 1..8 supported")
        if len(message.senders) != 1 or not 1 <= len(message.signals) <= 16:
            raise ValueError(f"{message.name}: one sender and 1..16 signals required")
        tx = message.senders == [config["node"]]
        if not tx and any(config["node"] not in s.receivers for s in message.signals):
            raise ValueError(f"{message.name}: RX signals must map to the policy node")
        settings = config["pdus"][message.name]
        keys(settings, ("mode", "period_ms", "min_delay_ms", "signals") if tx else
             ("timeout_ms",), message.name)
        mode, period, delay, timeout = "RX", 0, 0, 0
        if tx:
            mode = settings["mode"]
            if mode not in ("PERIODIC", "EVENT", "MIXED"):
                raise ValueError(f"{message.name}: unsupported TX mode")
            period = milliseconds(settings["period_ms"], "period_ms", mode == "EVENT")
            delay = milliseconds(settings["min_delay_ms"], "min_delay_ms", True)
            if mode == "EVENT" and period != 0:
                raise ValueError("EVENT requires period_ms=0")
            keys(settings["signals"], [s.name for s in message.signals], message.name)
        else:
            timeout = milliseconds(settings["timeout_ms"], "timeout_ms")
        pdu = dict(name=name, enum="CAN_PDU_" + name.upper(), message=message,
                   mode=mode, period=period, delay=delay, timeout=timeout,
                   first=len(signals), count=len(message.signals), tx=tx)
        signal_names = set()
        for signal in sorted(message.signals, key=lambda s: s.name):
            short = ident(signal.name)
            if short in signal_names:
                raise ValueError("duplicate normalized signal name")
            signal_names.add(short)
            if signal.is_multiplexer or signal.multiplexer_ids is not None:
                raise ValueError(f"{message.name}.{signal.name}: multiplexing is unsupported")
            if signal.is_float or not 1 <= signal.length <= 32 or signal.raw_invalid is not None:
                raise ValueError(f"{signal.name}: only integer signals of 1..32 bits without invalid markers supported")
            numeric = (signal.scale, signal.offset, signal.minimum, signal.maximum)
            if any(v is None or not math.isfinite(float(v)) for v in numeric) or signal.scale <= 0:
                raise ValueError(f"{signal.name}: positive finite scale and finite bounds required")
            scale, offset, low, high = map(lambda n: Decimal(str(n)), numeric)
            raw_min = -(1 << (signal.length - 1)) if signal.is_signed else 0
            raw_max = (1 << (signal.length - int(signal.is_signed))) - 1
            raw_min = max(raw_min, int(((low - offset) / scale).to_integral_value(rounding=ROUND_CEILING)))
            raw_max = min(raw_max, int(((high - offset) / scale).to_integral_value(rounding=ROUND_FLOOR)))
            initial = signal.raw_initial if signal.raw_initial is not None else min(max(0, raw_min), raw_max)
            if raw_min > raw_max or type(initial) is not int or not raw_min <= initial <= raw_max:
                raise ValueError(f"{signal.name}: empty bounds or invalid initial value")
            bits = bit_positions(signal)
            if any(bit < 0 or bit >= message.length * 8 for bit in bits):
                raise ValueError(f"{signal.name}: bit layout outside PDU")
            trigger = settings["signals"][signal.name] if tx else "PENDING"
            if trigger not in ("PENDING", "TRIGGERED_ON_CHANGE"):
                raise ValueError(f"{signal.name}: unsupported signal trigger")
            width = next(w for w in (8, 16, 32) if w >= signal.length)
            signals.append(dict(name=f"{name}_{short}", enum=f"CAN_SIGNAL_{name}_{short}".upper(),
                                pdu=pdu["enum"], bits=bits, signal=signal, low=raw_min,
                                high=raw_max, initial=initial, trigger=trigger,
                                ctype=f"{'int' if signal.is_signed else 'uint'}{width}_t", tx=tx))
        pdus.append(pdu)
    if len(signals) > 128:
        raise ValueError("at most 128 signals supported")
    if len({s["enum"] for s in signals}) != len(signals):
        raise ValueError("duplicate normalized full signal identifier")
    return pdus, signals


def generate(dbc, policy):
    pdus, signals = model(dbc, policy)
    enums = "typedef enum {\n" + "".join(f"\t{p['enum']},\n" for p in pdus) + "\tCAN_PDU_COUNT\n} can_pdu_id_t;\n"
    enums += "typedef enum {\n" + "".join(f"\t{s['enum']},\n" for s in signals) + "\tCAN_SIGNAL_COUNT\n} can_signal_id_t;\n"
    cfg_h = BANNER + """#ifndef ZEPHYRECU_CAN_CFG_H_
#define ZEPHYRECU_CAN_CFG_H_
#include <stdbool.h>
#include <stdint.h>
""" + enums + f"#define CAN_COMM_MAX_PDU_SIGNALS {max(p['count'] for p in pdus)}\n" + """
enum can_comm_mode { CAN_COMM_RX, CAN_COMM_PERIODIC, CAN_COMM_EVENT, CAN_COMM_MIXED };
struct can_pdu_cfg {
    uint32_t id;
    uint32_t period_ms, min_delay_ms, timeout_ms;
    uint16_t first_signal, signal_count;
    uint8_t dlc;
    bool extended;
    enum can_comm_mode mode;
};
struct can_signal_cfg {
    can_pdu_id_t pdu;
    uint8_t length, bits[32];
    bool is_signed, on_change;
    int64_t raw_min, raw_max, initial;
    double scale, offset;
};
extern const struct can_pdu_cfg can_pdu_config[CAN_PDU_COUNT];
extern const struct can_signal_cfg can_signal_config[CAN_SIGNAL_COUNT];
#endif
"""
    cfg_c = BANNER + '#include "can_cfg.h"\nconst struct can_pdu_cfg can_pdu_config[CAN_PDU_COUNT] = {\n'
    for p in pdus:
        m = p["message"]
        cfg_c += (f"    [{p['enum']}] = {{.id = 0x{m.frame_id:x}, .dlc = {m.length}, "
                  f".extended = {str(m.is_extended_frame).lower()}, .mode = CAN_COMM_{p['mode']}, "
                  f".period_ms = {p['period']}, .min_delay_ms = {p['delay']}, .timeout_ms = {p['timeout']}, "
                  f".first_signal = {p['first']}, .signal_count = {p['count']}}},\n")
    cfg_c += '};\nconst struct can_signal_cfg can_signal_config[CAN_SIGNAL_COUNT] = {\n'
    for s in signals:
        sig = s["signal"]
        cfg_c += (f"    [{s['enum']}] = {{.pdu = {s['pdu']}, .length = {sig.length}, "
                  f".bits = {{{', '.join(map(str, s['bits']))}}}, "
                  f".is_signed = {str(sig.is_signed).lower()}, .on_change = {str(s['trigger'] == 'TRIGGERED_ON_CHANGE').lower()}, "
                  f".raw_min = INT64_C({s['low']}), .raw_max = INT64_C({s['high']}), "
                  f".initial = INT64_C({s['initial']}), .scale = {float(sig.scale)!r}, .offset = {float(sig.offset)!r}}},\n")
    cfg_c += '};\n'
    sig_h = BANNER + """#ifndef ZEPHYRECU_CAN_SIGNALS_H_
#define ZEPHYRECU_CAN_SIGNALS_H_
#include "can_cfg.h"
/* Eight-byte buffers. Invalid IDs/pointers decode as zero; encode does nothing. */
int64_t can_signal_decode(can_signal_id_t id, const uint8_t data[8]);
void can_signal_encode(can_signal_id_t id, int64_t raw, uint8_t data[8]);
"""
    sig_c = BANNER + """#include "can_signals.h"
#include "can_comm.h"
#include <errno.h>
#include <stddef.h>

int64_t can_signal_decode(can_signal_id_t id, const uint8_t data[8])
{
    if ((unsigned int)id >= CAN_SIGNAL_COUNT || data == NULL) { return 0; }
    const struct can_signal_cfg *cfg = &can_signal_config[id];
    if (cfg->length == 0 || cfg->length > 32) { return 0; }
    uint64_t raw = 0;
    for (unsigned int i = 0; i < cfg->length; ++i) {
        unsigned int bit = cfg->bits[i];
        if ((data[bit / 8] & (1U << (bit % 8))) != 0) {
            raw |= UINT64_C(1) << i;
        }
    }
    if (cfg->is_signed && (raw & (UINT64_C(1) << (cfg->length - 1))) != 0) {
        return (int64_t)raw - (INT64_C(1) << cfg->length);
    }
    return (int64_t)raw;
}

void can_signal_encode(can_signal_id_t id, int64_t value, uint8_t data[8])
{
    if ((unsigned int)id >= CAN_SIGNAL_COUNT || data == NULL) { return; }
    const struct can_signal_cfg *cfg = &can_signal_config[id];
    if (cfg->length == 0 || cfg->length > 32) { return; }
    uint64_t raw = (uint64_t)value;
    for (unsigned int i = 0; i < cfg->length; ++i) {
        unsigned int bit = cfg->bits[i];
        uint8_t mask = (uint8_t)(1U << (bit % 8));
        data[bit / 8] = (uint8_t)((data[bit / 8] & (uint8_t)~mask) |
            (((raw >> i) & 1U) != 0 ? mask : 0));
    }
}
"""
    for s in signals:
        stem, ctype = "can_signal_" + s["name"], s["ctype"]
        sig_h += f"int {stem}_get_raw({ctype} *raw, bool *valid);\n"
        sig_c += f"""
int {stem}_get_raw({ctype} *raw, bool *valid)
{{
    can_comm_sample_t sample;
    if (raw == NULL || valid == NULL) {{ return -EINVAL; }}
    int ret = can_comm_get_signal({s['enum']}, &sample);
    if (ret == 0) {{ *raw = ({ctype})sample.raw; *valid = sample.valid; }}
    return ret;
}}
"""
        if s["tx"]:
            sig_h += f"int {stem}_set_raw({ctype} raw);\n"
            sig_c += f"""
int {stem}_set_raw({ctype} raw)
{{
    return can_comm_set_signal_raw({s['enum']}, raw);
}}
"""
    sig_h += '#endif\n'
    return dict(zip(("can_cfg.h", "can_cfg.c", "can_signals.h", "can_signals.c"),
                    (cfg_h, cfg_c, sig_h, sig_c)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dbc", type=Path, default=ROOT / "dbc/automotive.dbc")
    parser.add_argument("--policy", type=Path, default=ROOT / "dbc/can_policy.yaml")
    parser.add_argument("--out", type=Path, default=ROOT / "components/can_comm/generated")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        files = generate(args.dbc, args.policy)
        for name, content in files.items():
            path = args.out / name
            if args.check:
                if not path.is_file() or path.read_bytes() != content.encode():
                    raise ValueError(f"stale generated file: {path}; run tools/dbc_codegen.py")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content.encode())
    except (ValueError, OSError, yaml.YAMLError, cantools.database.errors.Error) as error:
        parser.exit(1, f"DBC generation failed: {error}\n")
    print("Generated CAN configuration matches inputs" if args.check else "Generated CAN configuration")


if __name__ == "__main__":
    main()
